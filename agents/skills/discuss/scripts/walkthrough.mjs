// 挑错轮的题面必须带【推演】段：从创始人的角度把全程走一遍、按阶段列边界和最坏情况、写上对照的成熟案例。
// 起因（创始人 2026-09-26）：「你好像把思考也当成做事情了……没有想着去验证一下这个思路」——
// 方案没推演就拿去挑错、交人拍，漏洞全靠他挑（统领单「开工后自动挂子单」会让母单永远关不掉，就是这么漏的）。
export function missingWalkthrough(text) {
  const m = /【推演】([\s\S]*?)(?=\n【|$)/.exec(String(text ?? ''));
  if (!m)
    return '题面缺【推演】段：挑错前先从创始人的角度把全程走一遍、按阶段列边界和最坏情况、写上对照的成熟案例';
  if (m[1].replace(/\s+/g, '').length < 80)
    return '【推演】段不到 80 字：要写全程怎么走、各阶段的边界和最坏情况、对照的案例';
  return null;
}
